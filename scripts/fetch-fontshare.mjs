/**
 * Downloads the Fontshare faces we use (Indian Type Foundry, free for
 * commercial use) into public/fonts and writes public/fonts/fontshare.css.
 *
 * Self-hosting keeps the runtime free of third-party font requests, which is
 * both a privacy win and what stops a slow CDN from delaying first paint.
 *
 * Re-run after changing the WANTED list:  node scripts/fetch-fontshare.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';

/** slug -> weights. The slug must match the family the API returns. */
const WANTED = [
  ['zodiak', 'Zodiak', [400, 700]],
  ['gambetta', 'Gambetta', [400, 500]],
  ['erode', 'Erode', [400, 500]],
  ['bespoke-serif', 'Bespoke Serif', [400, 500]],
  ['clash-display', 'Clash Display', [500, 600]],
  ['satoshi', 'Satoshi', [400, 500, 700]],
  ['general-sans', 'General Sans', [400, 500, 600]],
  ['switzer', 'Switzer', [400, 500, 600]],
  ['cabinet-grotesk', 'Cabinet Grotesk', [500, 700]],
];

mkdirSync('public/fonts', { recursive: true });

let css =
  '/* Fontshare (Indian Type Foundry) — free for commercial use.\n' +
  ' * Generated by scripts/fetch-fontshare.mjs. Do not edit by hand.\n */\n';

for (const [slug, family, weights] of WANTED) {
  // One request per family: a combined request returns every family in the
  // sheet, and matching by position silently mislabels the files.
  const url = `https://api.fontshare.com/v2/css?f[]=${slug}@${weights.join(',')}&display=swap`;
  const sheet = await (await fetch(url)).text();
  const got = new Set();

  for (const block of sheet.split('@font-face').slice(1)) {
    const fam = block.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
    const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? 'normal';
    const woff2 = block.match(/url\('(\/\/[^']+\.woff2)'\)/)?.[1];

    // Only keep the family this request was for, at the weights we asked for.
    if (fam !== family || !weight || !woff2) continue;
    if (style !== 'normal' || !weights.includes(Number(weight))) continue;

    const file = `${slug}-${weight}.woff2`;
    const bytes = Buffer.from(await (await fetch(`https:${woff2}`)).arrayBuffer());
    writeFileSync(`public/fonts/${file}`, bytes);
    got.add(Number(weight));
    css +=
      `@font-face{font-family:'${fam}';src:url('/fonts/${file}') format('woff2');` +
      `font-weight:${weight};font-style:normal;font-display:swap;}\n`;
  }

  // A family that does not publish a requested weight would otherwise emit no
  // @font-face for it and fall back silently at runtime.
  const missing = weights.filter((w) => !got.has(w));
  if (missing.length) {
    console.warn(`  ! ${family}: no ${missing.join(', ')} — check available weights`);
  }
}

writeFileSync('public/fonts/fontshare.css', css);
console.log('Fontshare faces written to public/fonts');
